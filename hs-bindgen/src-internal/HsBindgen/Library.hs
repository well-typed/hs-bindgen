{-------------------------------------------------------------------------------
  Library headers
-------------------------------------------------------------------------------}

-- | A library, as the user describes it
data Library = Library {
      -- | The directories that hold the headers of the library
      dirs :: NonEmpty FilePath
    }
  deriving stock (Show, Eq)

-- | The path of a header below its library directory
--
-- For example @mylib\/types.h@, as a list of its components.  It does not say
-- where the library is, and it reads the same on every platform.
newtype LibraryPath = LibraryPath (NonEmpty String)
  deriving stock (Show, Eq, Ord)

-- | The path with @\/@ between its components, on every platform
renderLibraryPath :: LibraryPath -> String
renderLibraryPath (LibraryPath components) =
    List.intercalate "/" (NonEmpty.toList components)

instance PrettyForTrace LibraryPath where
  prettyForTrace = PP.string . renderLibraryPath

-- | The directories of the library that do not exist
missingDirs :: Library -> IO [FilePath]
missingDirs library =
    filterM (fmap not . doesDirectoryExist) (NonEmpty.toList library.dirs)

-- | The library headers among the given headers
--
-- A header is a library header if it is in a directory of the library, at any
-- depth.  When directories of the library nest, the path is the one below the
-- outermost: with the directories @lib@ and @lib/sub@, @lib/sub/a.h@ is
-- @sub/a.h@.
--
-- Both the directories and the headers are made canonical in the same way
-- before they are compared, so that it does not matter how a directory was
-- written on the command line.
libraryPaths :: Library -> [RealPath] -> IO (Map RealPath LibraryPath)
libraryPaths library headers = do
    dirs <- mapM canonicalizePath (NonEmpty.toList library.dirs)
    fmap (Map.fromList . catMaybes) $ forM headers $ \header -> do
      file <- canonicalizePath (getRealPath header)
      pure $ (header,) <$>
        pathBelow FilePath.splitDirectories FilePath.equalFilePath dirs file

-- | The path of a file below the outermost of the directories that it is in
--
-- How paths are split and compared depends on the platform, so both are
-- arguments.
pathBelow ::
     (FilePath -> [FilePath])        -- ^ The components of a path
  -> (FilePath -> FilePath -> Bool)  -- ^ Are two components the same?
  -> [FilePath]                      -- ^ Directories
  -> FilePath                        -- ^ File
  -> Maybe LibraryPath
pathBelow split same dirs file =
      fmap LibraryPath
    . listToMaybe
    . mapMaybe NonEmpty.nonEmpty
      -- The outermost directory leaves the longest path
    . List.sortOn (Down . length)
    $ mapMaybe (\dir -> below (split dir) (split file)) dirs
  where
    below :: [FilePath] -> [FilePath] -> Maybe [FilePath]
    below []       rest     = Just rest
    below (_ : _)  []       = Nothing
    below (d : ds) (c : cs)
      | same d c  = below ds cs
      | otherwise = Nothing

{-------------------------------------------------------------------------------
  Module names
-------------------------------------------------------------------------------}

-- | The name of the module for a header
--
-- The base module, followed by the components of the path, the last one
-- without its extension.  A component becomes a part of a module name much as
-- a C name becomes a Haskell type name: the first letter is made upper case,
-- and a name that cannot start a type name gets a @C@ in front.  A character
-- that cannot be in a name becomes @_@.  With the base module @Lib@:
--
-- > types.h        Lib.Types
-- > mylib/types.h  Lib.Mylib.Types
-- > foo-bar.h      Lib.Foo_bar
-- > 3d.h           Lib.C3D
--
-- There is no name if a component has none, as for a header called @.h@.
moduleName :: BaseModuleName -> LibraryPath -> Maybe BaseModuleName
moduleName base (LibraryPath components) = do
    names <- traverse part (NonEmpty.toList withoutExtension)
    pure $ BaseModuleName $ Text.intercalate "." (base.text : names)
  where
    withoutExtension :: NonEmpty String
    withoutExtension = case NonEmpty.reverse components of
      file :| dirs -> NonEmpty.reverse (FilePath.dropExtension file :| dirs)

    part :: String -> Maybe Text
    part component =
        (.text) <$> typeName (Text.pack component)

    -- For a C name, a character that cannot be in a Haskell name is escaped,
    -- so that two C names never get one Haskell name.  A module name is read
    -- and typed by people, who are better off with an underscore; two headers
    -- that get one name this way are reported.
    typeName :: Text -> Maybe (Hs.Name Hs.NsTypeConstr)
    typeName = mangleCandidate mangleCandidateDefault{
          onInvalidChar = const (Just "_")
        }

{-------------------------------------------------------------------------------
  Ownership
-------------------------------------------------------------------------------}

-- | The library header that owns each declaration
--
-- A declaration is owned by the library header that it is located in, if the
-- predicate selects it.  Selecting has the meaning that it has in the @Select@
-- pass: a declaration with an external binding or one that a prescriptive
-- binding specification omits is not selected, and so nobody owns it; an
-- unnamed declaration is selected with the declaration that uses it.  The
-- predicate is matched as that pass matches it too.  What it says about
-- headers is about the header that a declaration is located in, and about the
-- main headers, which are given for that.
--
-- A typedef that is squashed into a struct is one declaration with that
-- struct, and one type in Haskell.  The two have the same owner: the header
-- that the struct is located in or, if that is not a library header, the
-- header that the typedef is located in.  In
--
-- > // types.h                      // point.h
-- > typedef struct point point;     #include "types.h"
-- > typedef int status;             struct point { int x; int y; };
--
-- point.h owns the type and types.h owns @status@.  If each owned what is
-- located in it, the typedef would make types.h use point.h, and a struct of
-- point.h that used @status@ would tie the two headers into one module.
--
-- The two are still selected one by one, each where it is located.  A
-- predicate that leaves out the declarations of point.h still selects the
-- typedef, so point.h still owns the type and still gets a module.
owners :: forall l.
     (RealPath -> Bool)          -- ^ Is this a library header?
  -> Set RealPath                -- ^ The main headers
  -> Boolean SelectionPredicate
  -> DeclMeta l
  -> Map C.DeclId RealPath
owners isLibraryHeader mainHeaders predicate meta =
    Map.restrictKeys home (DeclIndex.keysSet selected)
  where
    selected :: DeclIndex.DeclIndex l
    selected = selectDeclIndex meta.declUseGraph match meta.declIndex

    match :: Match
    match name loc availability =
           C.DeclId{name = name, isUnnamed = False} `Map.member` home
        && matchSelect
             (mkIsMainHeader mainHeaders)
             (mkIsInMainHeaderDir mainHeaders)
             (singleLocPath loc)
             name
             availability
             predicate

    -- The header that would own each declaration
    home :: Map C.DeclId RealPath
    home = Map.union together located

    -- Each declaration on its own: the library header that it is located in
    located :: Map C.DeclId RealPath
    located = Map.fromList [
          (declId, header)
        | (declId, entry) <- DeclIndex.toList meta.declIndex
        , header : _ <- [
              mapMaybe libraryHeader $
                C.declLocsToList (DeclIndex.entryToLoc entry)
            ]
        ]

    -- A squashed typedef together with its struct
    together :: Map C.DeclId RealPath
    together = Map.fromList $ concat [
          [(typedef, header), (struct, header)]
        | (typedef, UsableEntry (UsableSquashed squashed))
            <- DeclIndex.toList meta.declIndex
        , let struct = squashed.targetNameC
        , Just header <- [
              Map.lookup struct located <|> Map.lookup typedef located
            ]
        ]

    libraryHeader :: SingleLoc C.DeclPath -> Maybe RealPath
    libraryHeader loc = case singleLocPath loc of
      C.InHeader path | isLibraryHeader path -> Just path
      _otherwise                             -> Nothing

-- | The main headers: the ones that were given, not the ones that they include
mainHeadersOf :: IncludeGraph -> Set RealPath
mainHeadersOf = Set.fromList . Map.elems . IncludeGraph.mainHeaders

{-------------------------------------------------------------------------------
  Modules
-------------------------------------------------------------------------------}

-- | Why a library cannot be generated as one module per header
data LibraryError =
    -- | None of the headers that were read is in a directory of the library
    NoLibraryHeader

    -- | The header has no name that a module could be named after
  | NoModuleName LibraryPath

    -- | The headers use each other, so that none of their modules can be
    -- generated first
  | HeadersUseEachOther (NonEmpty LibraryPath)
  deriving stock (Show, Eq)

instance PrettyForTrace LibraryError where
  prettyForTrace = \case
    NoLibraryHeader -> PP.vcat [
        "None of the headers that were read is in a library directory."
      , PP.hsep [
            "A library header is one of the given headers, or a header that"
          , "they include, that is in a --library directory."
          ]
      ]
    NoModuleName header ->
      "There is no module name for library header" <+> prettyForTrace header
    HeadersUseEachOther headers -> PP.hangs'
      ( PP.hsep [
            "These library headers use each other,"
          , "so no module can be generated first:"
          ]
      )
      2
      (map prettyForTrace (NonEmpty.toList headers))

-- | The modules that a library is generated as, in the order of generation
--
-- Each module comes with its name.  The declarations that a header owns are
-- those that the predicate selects ('owners').
modules ::
     forall l.
     BaseModuleName
  -> Map RealPath LibraryPath
     -- ^ The library headers ('libraryPaths')
  -> IncludeGraph
  -> Boolean SelectionPredicate
  -> DeclMeta l
  -> Either LibraryError [(BaseModuleName, Module LibraryPath C.DeclId)]
modules base paths includeGraph predicate meta
    | Map.null paths = Left NoLibraryHeader
    | otherwise      = mapM named . mapMaybe inLibrary $ Plan.plan Uses{
          owner    = owners
                       (`Map.member` paths)
                       (mainHeadersOf includeGraph)
                       predicate
                       meta
        , uses     = UseDeclGraph.getTransitiveDeps meta.useDeclGraph
        , includes = \header -> Map.findWithDefault Set.empty header included
        , order    = filter (`Map.member` paths) $
                       IncludeGraph.toSortedList includeGraph
        }
  where
    -- The plan is made for the files.  Two of them can have the same path
    -- below their library directories, and they are still two headers.
    --
    -- Every header of the plan owns a declaration, so it is a library header
    -- and has a path.
    inLibrary :: Module RealPath C.DeclId -> Maybe (Module LibraryPath C.DeclId)
    inLibrary m = do
        headers <- traverse libraryPath m.headers
        pure Module{
            headers = headers
          , decls   = m.decls
          , uses    = Set.fromList (mapMaybe libraryPath (Set.toList m.uses))
          }

    libraryPath :: RealPath -> Maybe LibraryPath
    libraryPath = (`Map.lookup` paths)

    named ::
         Module LibraryPath C.DeclId
      -> Either LibraryError (BaseModuleName, Module LibraryPath C.DeclId)
    named m = case m.headers of
      header :| [] -> case moduleName base header of
        Just name -> Right (name, m)
        Nothing   -> Left (NoModuleName header)
      headers      -> Left (HeadersUseEachOther headers)

    -- The library headers that a library header includes, directly or
    -- indirectly
    included :: Map RealPath (Set RealPath)
    included = Map.fromListWith Set.union [
          (includer, Set.singleton header)
        | header   <- Map.keys paths
        , includer <- Set.toList (IncludeGraph.reaches includeGraph header)
        , includer /= header
        , includer `Map.member` paths
        ]
