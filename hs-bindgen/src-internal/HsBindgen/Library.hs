-- | A C library as one Haskell module per header
--
-- Which headers belong to the library, what each of them owns, and which
-- modules that makes.  How the modules are ordered is the business of
-- "HsBindgen.Library.Plan"; how they are generated, that of
-- 'HsBindgen.forEachModule'.
--
-- A /library header/ is a header that is read and that is in a directory of
-- the library.  It /owns/ the declarations that are located in it and that
-- are selected, and a header that owns something gets a module.  A
-- declaration that nobody owns, from outside the library or not selected, is
-- generated by the first module that needs it.  For a library with
--
-- > // draw.h                        // shape.h
-- > struct shape;                    struct shape { int sides; };
-- > int draw(struct shape *s);
--
-- shape.h owns @struct shape@ and draw.h owns @draw@: two modules.  When the
-- declarations of shape.h are not selected, shape.h owns nothing and gets no
-- module, and @Shape@ is generated by the module of draw.h, which needs it.
--
-- Intended for qualified import.
--
-- > import HsBindgen.Library (Library (..), LibraryPath)
-- > import HsBindgen.Library qualified as Library
module HsBindgen.Library (
    -- * Library headers
    Library(..)
  , LibraryPath(..)
  , renderLibraryPath
  , missingDirs
  , libraryPaths
  , pathBelow
    -- * Module names
  , moduleName
    -- * Ownership
  , owners
    -- * Modules
  , LibraryError(..)
  , modules
  ) where

